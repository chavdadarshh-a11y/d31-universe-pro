// Generates supabase/migrations/0003_seed_exercises.sql from src/data/exercises.ts
// (and inserts the sample d31_posts) so the database matches the app.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = readFileSync(join(root, 'src/data/exercises.ts'), 'utf8')
const body = src.slice(src.indexOf('= [') + 2, src.lastIndexOf(']\n\nexport const EX_BY_ID') + 1)
const EXERCISES = Function(`return ${body}`)()

const q = (s) => (s === null || s === undefined ? 'null' : `'${String(s).replace(/'/g, "''")}'`)
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`

let sql = '-- AUTO-GENERATED by scripts/gen-seed.mjs — do not edit by hand.\n-- Exercise library seed (' + EXERCISES.length + ' exercises)\n\n'
for (const e of EXERCISES) {
  sql += `insert into public.exercises (id,name,name_hi,name_gu,category,equipment,level,layer,tracking,primary_muscles,secondary_muscles,summary,steps,cues,mistakes,benefits) values (${[
    q(e.id), q(e.name), q(e.nameHi), q(e.nameGu), q(e.category), arr(e.equipment), e.level, q(e.layer), q(e.tracking),
    arr(e.primary), e.secondary.length ? arr(e.secondary) : `'{}'::text[]`, q(e.summary), arr(e.steps), arr(e.cues), arr(e.mistakes), arr(e.benefits),
  ].join(',')})\non conflict (id) do update set name=excluded.name,name_hi=excluded.name_hi,name_gu=excluded.name_gu,category=excluded.category,equipment=excluded.equipment,level=excluded.level,layer=excluded.layer,tracking=excluded.tracking,primary_muscles=excluded.primary_muscles,secondary_muscles=excluded.secondary_muscles,summary=excluded.summary,steps=excluded.steps,cues=excluded.cues,mistakes=excluded.mistakes,benefits=excluded.benefits;\n`
}
writeFileSync(join(root, 'supabase/migrations/0003_seed_exercises.sql'), sql)
console.log(`wrote ${EXERCISES.length} exercises → supabase/migrations/0003_seed_exercises.sql`)
