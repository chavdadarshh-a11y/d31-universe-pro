/** Built-in + the user's own custom exercises. */
export function allExercises(): Exercise[] {
  return [...useApp.getState().customExercises, ...EXERCISES]
}

/** Look up any exercise (built-in or custom). Never returns undefined, so old logs can't crash a screen. */
export function exOf(id: string): Exercise {
  return EX_BY_ID[id] ?? useApp.getState().customExercises.find((e) => e.id === id) ?? { ...UNKNOWN, id, name: id, nameHi: id, nameGu: id }
}

export function exName(e: Exercise, lang: 'en' | 'hi' | 'gu'): string {
  return lang === 'hi' ? e.nameHi : lang === 'gu' ? e.nameGu : e.name
}
